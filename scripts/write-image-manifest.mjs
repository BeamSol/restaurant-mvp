/**
 * Writes IMAGE_MANIFEST.md from supabase/seed/image-manifest.json
 * (produced by process-images.mjs) + the list of photos we still need.
 *   node scripts/write-image-manifest.mjs
 */
import { readFile, writeFile } from "node:fs/promises";

const rows = JSON.parse(await readFile("supabase/seed/image-manifest.json", "utf8"));
const missing = [
  ["Branch: Unity Park", "Photo of the Unity Park branch (outside + inside)"],
  ["Branch: 22 Area", "Photo of the 22 Area branch"],
  ["Branch: Meskel Flower", "Photo of the Meskel Flower branch"],
  ["Branch: Catering Bole Moenco", "Photo of the catering kitchen / delivery setup (current photo shows food only)"],
  ["Mama's Inn", "Real room photos (currently STOCK)"],
  ["Menu: most dishes", "Only 10 of ~57 dishes have a photo; priority: national dishes (Dullet, Bozena Shiro, Tibs Firfir), Steaks, Soups, Fish"],
  ["Coffee / special tea", "Their own coffee ceremony photo (currently STOCK)"],
  ["Hero", "A new high-resolution (≥1600px) photo; the current hero is 1280px from 2021"],
  ["Logo", "Original vector logo (SVG/AI/PDF); current file is a 390px PNG"],
];
const esc = (s = "") => String(s).replace(/\|/g, "\\|");
let md = `# Image manifest

Every image on the website, where it came from, and whether we may use it publicly.
Generated by \`node scripts/write-image-manifest.mjs\`. Do not edit the tables by hand.

**Status legend**
- **OFFICIAL**: from Mama's Kitchen's own website (mamaskitchenethiopia.com, via the Internet Archive). Their own brand assets: fine for a private demo **to them**. **Get the owner's written OK before public launch.** Most carry their red logo watermark and are ≤ 960px (2016–2021 photos).
- **OFFICIAL?**: on their site, but it looks like a generic stock photo from their old WordPress theme. Replace.
- **STOCK – replace**: free photo from Unsplash (Unsplash License: free for commercial use, no attribution required). Used only where they have no photo. Replace with their own photos.
- **NEEDS PHOTO**: nothing suitable exists yet. The site currently shows a related official photo.

Rules followed: images are downloaded into \`/public/restaurant/\` (no hotlinking), converted to WebP, hero ≤ 250 KB, cards ≤ 120 KB, never upscaled, blur placeholders generated (\`supabase/seed/images.json\`). No photos were taken from Tripadvisor, Google reviews, customer posts or other restaurants.

## Images in use (${rows.length})

| File | Size | Used in | Status | Source | Notes |
|---|---|---|---|---|---|
`;
for (const r of rows) md += `| \`${r.file}\` | ${r.width}×${r.height}, ${r.kb} KB | ${esc(r.use)} | **${r.status}** | ${esc(r.source)} | ${esc(r.note)} |\n`;
md += `| \`/restaurant/logo.png\` | 390×257 | Header, footer, favicon, palette | **OFFICIAL** | https://web.archive.org/web/20180814054513/http://mamaskitchenethiopia.com/wp-content/uploads/2018/05/logo-tiff.png | Largest version available |
| \`/restaurant/og.jpg\` | 1200×630 | Social share preview | **OFFICIAL** (generated) | hero.webp + logo.png | |

## Still needed (${missing.length})

| Where | What we need |
|---|---|
${missing.map(([a, b]) => `| ${a} | ${b} |`).join("\n")}

## Summary
- OFFICIAL: ${rows.filter((r) => r.status === "OFFICIAL").length + 2}
- OFFICIAL? (probably theme stock): ${rows.filter((r) => r.status === "OFFICIAL?").length}
- STOCK – replace: ${rows.filter((r) => r.status.startsWith("STOCK")).length}
- NEEDS PHOTO: ${missing.length}
`;
await writeFile("IMAGE_MANIFEST.md", md);
console.log("IMAGE_MANIFEST.md written:", rows.length, "images");
